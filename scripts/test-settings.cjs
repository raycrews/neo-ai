  assert.equal(await evaluate(win, 'state.defaultId === selectedId && state.profiles.length === 2'), true);
  assert.equal(await evaluate(win, 'state.profiles.find(p=>p.id===selectedId).keyStatus'), 'none');
  await evaluate(win, 'window.confirm=()=>true; true'); await click('#delete-profile');
  await until(() => evaluate(win, `!busy && selectedId === ${JSON.stringify(firstId)}`), 'default restored after deleting second profile');
  assert.equal(fs.readFileSync(path.join(userData, 'ai-connections.json'), 'utf8').includes('secret-fixture-key'), false);
