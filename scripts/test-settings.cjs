// Real Electron settings UI with a local mock server and isolated app data.
const { app, BrowserWindow, dialog } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'neo-ai-settings-'));
const userData = path.join(scratch, 'device');
const libraryDir = path.join(scratch, 'library');
fs.mkdirSync(userData, { recursive: true }); fs.mkdirSync(libraryDir);
fs.writeFileSync(path.join(userData, 'settings.json'), JSON.stringify({ libraryDir }));
fs.writeFileSync(path.join(libraryDir, 'library.json'), JSON.stringify({ firstRunDone: true, authorName: 'Test', shelves: [], coverArt: { auto: false } }));
app.setPath('userData', userData);
process.env.NEO_TEST_HEADLESS = '1';
if (process.platform === 'linux') app.commandLine.appendSwitch('no-sandbox');
const requests = []; let mode = 'normal';
const server = http.createServer(async (req, res) => {
  let body = ''; for await (const chunk of req) body += chunk;
  requests.push({ url: req.url, auth: req.headers.authorization, body });
  if (mode === 'slow') return;
  res.setHeader('Content-Type', 'application/json');
  if (mode === 'auth') { res.writeHead(401); res.end(JSON.stringify({ error: 'do not echo secret-fixture-key' })); return; }
  if (req.url === '/v1/models') res.end(JSON.stringify({ data: [{ id: 'fixture-model' }, { id: 'another-model' }] }));
  else if (req.url === '/v1/responses') res.end(JSON.stringify({ output: [{ content: [{ type: 'output_text', text: 'Connected' }] }] }));
  else res.end(JSON.stringify({ choices: [{ message: { content: 'Connected' } }] }));
});
server.listen(0, '127.0.0.1');
require('../main');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const evaluate = (win, code) => win.webContents.executeJavaScript(code, true);
