  const click = selector => evaluate(win, `document.querySelector(${JSON.stringify(selector)}).click()`);
  await click('[data-page="ai"]');
  await until(() => evaluate(win, 'document.querySelector("#assistant-type").options.length === 6'), 'assistant instructions');
  await edit('#assistant-type', 'characters');
  await evaluate(win, 'document.querySelector("#assistant-type").dispatchEvent(new Event("change"))');
  await edit('#assistant-instructions', 'Ask about character motivations.');
  await click('#save-assistant');
  await until(() => evaluate(win, 'document.querySelector("#assistant-status").textContent.includes("Instructions saved")'), 'instructions saved');
  assert.equal(JSON.parse(fs.readFileSync(path.join(userData, 'ai-assistants.json'))).instructions.characters, 'Ask about character motivations.');
  await click('#restore-assistant');
  assert.notEqual(await evaluate(win, 'document.querySelector("#assistant-instructions").value'), 'Ask about character motivations.');
